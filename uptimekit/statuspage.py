"""Self-contained HTML status page from probe history.

One file in, one file out: no JS, no external CSS, no web framework - the
output can be served from any static host or opened straight from disk.
Everything is escaped; history is operational data, not markup.
"""

import html
import time

from .availability import availability, current_state
from .history import Entry

TICKS = 30  # recent checks shown as a tick strip per target

_CSS = """
:root { color-scheme: light dark; }
body { font-family: system-ui, sans-serif; max-width: 760px; margin: 2rem auto; padding: 0 1rem; }
h1 { font-size: 1.4rem; }
.banner { padding: .6rem 1rem; border-radius: 8px; font-weight: 600; }
.banner.up { background: #dafbe1; color: #116329; }
.banner.down { background: #ffebe9; color: #a40e26; }
.target { border: 1px solid #8884; border-radius: 8px; padding: .8rem 1rem; margin: .8rem 0; }
.head { display: flex; justify-content: space-between; align-items: baseline; }
.state { font-weight: 600; text-transform: uppercase; font-size: .8rem; }
.state.up { color: #1a7f37; } .state.down { color: #cf222e; } .state.unknown { color: #9a6700; }
.ticks { display: flex; gap: 2px; margin: .5rem 0; }
.tick { flex: 1; height: 14px; border-radius: 2px; background: #8884; }
.tick.ok { background: #2da44e; } .tick.fail { background: #cf222e; }
.meta { color: #888; font-size: .85rem; }
footer { color: #888; font-size: .8rem; margin-top: 2rem; }
"""


def _fmt_time(ts: float) -> str:
    return time.strftime("%Y-%m-%d %H:%M:%S", time.localtime(ts))


def _tick_strip(entries: list[Entry], name: str) -> str:
    """Recent checks as colored ticks, oldest left, newest right."""
    mine = [e for e in entries if e.name == name][-TICKS:]
    if not mine:
        return '<div class="ticks"><div class="tick"></div></div>'
    ticks = "".join(
        f'<div class="tick {"ok" if e.ok else "fail"}" '
        f'title="{html.escape(_fmt_time(e.checked_at))}: {html.escape(e.detail)}"></div>'
        for e in mine)
    pad = f'<div class="tick"></div>' * (TICKS - len(mine))
    return f'<div class="ticks">{pad}{ticks}</div>'


def render(entries: list[Entry], names: list[str], window_label: str,
           now: float | None = None) -> str:
    """Render the status page for the given targets."""
    now = time.time() if now is None else now
    states = {name: current_state(entries, name) for name in names}
    down = [n for n, s in states.items() if s == "down"]
    if not down:
        banner = '<div class="banner up">All systems operational</div>'
    else:
        banner = (f'<div class="banner down">{len(down)} system'
                  f'{"s" if len(down) != 1 else ""} down: '
                  f'{html.escape(", ".join(down))}</div>')
    sections = []
    for name in names:
        a = availability([e for e in entries if e.name == name], name)
        state = states[name]
        if a.checks:
            summary = (f"{a.uptime_pct:.2f}% uptime over {a.checks} checks "
                       f"({window_label})")
        else:
            summary = "no checks recorded yet"
        last = [e for e in entries if e.name == name]
        last_line = (f"last check {html.escape(_fmt_time(last[-1].checked_at))}: "
                     f"{html.escape(last[-1].detail)}") if last else "never checked"
        sections.append(f"""<div class="target">
<div class="head"><strong>{html.escape(name)}</strong>
<span class="state {state}">{state}</span></div>
{_tick_strip(entries, name)}
<div class="meta">{summary}<br>{last_line}</div>
</div>""")
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Service status</title>
<style>{_CSS}</style>
</head>
<body>
<h1>Service status</h1>
{banner}
{"".join(sections)}
<footer>Generated by uptimekit at {html.escape(_fmt_time(now))} &middot;
window: {html.escape(window_label)} &middot; refresh by re-running
<code>uptimekit status-page</code></footer>
</body>
</html>
"""
